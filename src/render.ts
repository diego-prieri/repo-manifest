import { existsSync, readFileSync } from 'node:fs';
import { join, posix } from 'node:path';
import type { ManifestConfig } from './config.js';
import type { ExportedSymbol, RepoScan, SourceFile } from './scan.js';

const KIND_ORDER = ['component', 'hook', 'function', 'class', 'interface', 'type', 'enum', 'const'];

function formatSymbol(s: ExportedSymbol): string {
  return s.detail ? `\`${s.name}${s.kind === 'interface' ? ' ' : ''}${s.detail}\`` : `\`${s.name}\``;
}

function groupByDir(files: SourceFile[]): Map<string, SourceFile[]> {
  const groups = new Map<string, SourceFile[]>();
  for (const f of files) {
    const dir = posix.dirname(f.path);
    groups.set(dir, [...(groups.get(dir) ?? []), f]);
  }
  return groups;
}

function renderDir(dir: string, files: SourceFile[], max: number): string[] {
  const lines = [`### \`${dir}/\``];
  let shown = 0;
  let total = 0;
  for (const f of files) {
    total += f.exports.length;
    if (shown >= max) continue;
    const sorted = [...f.exports].sort((a, b) => KIND_ORDER.indexOf(a.kind) - KIND_ORDER.indexOf(b.kind));
    const visible = sorted.slice(0, max - shown);
    shown += visible.length;
    const byKind = KIND_ORDER.map((k) => {
      const of = visible.filter((s) => s.kind === k);
      return of.length ? `${k}: ${of.map(formatSymbol).join(', ')}` : '';
    }).filter(Boolean);
    lines.push(`- \`${posix.basename(f.path)}\` — ${byKind.join(' · ')}`);
  }
  if (total > shown) lines.push(`- …${total - shown} more exports omitted`);
  return lines;
}

export function renderMarkdown(scan: RepoScan, config: ManifestConfig): string {
  const out: string[] = [
    `# Repo manifest${scan.pkg?.name ? `: ${scan.pkg.name}` : ''}`,
    '',
    '> Generated by repo-manifest. A compact map of this codebase for AI agents: read it before',
    '> writing code, and prefer the existing symbols listed here over inventing new ones.',
    '',
  ];

  if (scan.pkg) {
    out.push('## Stack', '', `- Dependencies: ${scan.pkg.dependencies.join(', ') || '—'}`, `- Dev: ${scan.pkg.devDependencies.join(', ') || '—'}`, '');
    const scripts = Object.entries(scan.pkg.scripts);
    if (scripts.length) {
      out.push('## Scripts', '', ...scripts.map(([k, v]) => `- \`${k}\`: \`${v}\``), '');
    }
  }

  const aliases = Object.entries(scan.pathAliases);
  if (aliases.length) {
    out.push('## Import aliases', '', ...aliases.map(([k, v]) => `- \`${k}\` → \`${v.join(', ')}\``), '');
  }

  const counts = new Map<string, number>();
  for (const f of scan.files) for (const s of f.exports) counts.set(s.kind, (counts.get(s.kind) ?? 0) + 1);
  out.push(
    '## Exports',
    '',
    `${scan.files.length} files · ` + KIND_ORDER.filter((k) => counts.get(k)).map((k) => `${counts.get(k)} ${k}`).join(' · '),
    '',
  );
  for (const [dir, files] of groupByDir(scan.files)) {
    out.push(...renderDir(dir, files, config.maxExportsPerDir), '');
  }

  for (const note of config.notes) {
    const path = join(scan.root, note);
    if (existsSync(path)) out.push(`## Notes: ${note}`, '', readFileSync(path, 'utf8').trim(), '');
  }

  return out.join('\n').trimEnd() + '\n';
}
